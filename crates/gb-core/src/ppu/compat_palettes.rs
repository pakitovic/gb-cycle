#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct CgbCompatibilityPaletteSeed {
    pub(crate) lookup_index: u8,
    pub(crate) boot_input_override_index: Option<u8>,
    pub(crate) palette_index_and_flags: u8,
    pub(crate) palette_triplet_index: u8,
    pub(crate) shuffle_flags: u8,
    pub(crate) obj_palette0: [u8; PALETTE_ENTRY_BYTES],
    pub(crate) obj_palette1: [u8; PALETTE_ENTRY_BYTES],
    pub(crate) bg_palette0: [u8; PALETTE_ENTRY_BYTES],
}

impl CgbCompatibilityPaletteSeed {
    #[cfg(test)]
    pub(crate) fn bg_rgb555(self, color_index: u8) -> u16 {
        rgb555_from_palette_bytes(&self.bg_palette0, color_index)
    }

    #[cfg(test)]
    pub(crate) fn obj_rgb555(self, palette_obp1: bool, color_index: u8) -> u16 {
        let palette = if palette_obp1 {
            &self.obj_palette1
        } else {
            &self.obj_palette0
        };
        rgb555_from_palette_bytes(palette, color_index)
    }
}

#[cfg(test)]
pub(crate) fn resolve_cgb_compatibility_palette_seed(
    header: Option<&CartridgeHeader>,
) -> CgbCompatibilityPaletteSeed {
    resolve_cgb_compatibility_palette_seed_with_input(
        header,
        CgbCompatibilityPaletteBootInput::none(),
    )
}

pub(crate) fn resolve_cgb_compatibility_palette_seed_with_input(
    header: Option<&CartridgeHeader>,
    boot_input: CgbCompatibilityPaletteBootInput,
) -> CgbCompatibilityPaletteSeed {
    let lookup_index = resolve_lookup_index(header);
    let boot_input_override_index = boot_input.override_index();
    let palette_index_and_flags = boot_input_override_index.map_or_else(
        || PALETTE_INDEXES_AND_FLAGS[usize::from(lookup_index)],
        |index| BOOT_INPUT_PALETTE_INDEXES_AND_FLAGS[index],
    );
    let palette_triplet_index = palette_index_and_flags & 0x1F;
    let shuffle_flags = palette_index_and_flags >> 5;
    let base = usize::from(palette_triplet_index) * 3;
    let first = PALETTE_INDEXES[base];
    let second = PALETTE_INDEXES[base + 1];
    let third = PALETTE_INDEXES[base + 2];
    let obj0_offset = if shuffle_flags & 0x01 != 0 {
        first
    } else {
        third
    };
    let obj1_offset = if shuffle_flags & 0x04 != 0 {
        second
    } else if shuffle_flags & 0x02 != 0 {
        first
    } else {
        third
    };
    let bg_offset = third;

    CgbCompatibilityPaletteSeed {
        lookup_index,
        boot_input_override_index: boot_input_override_index.map(|index| index as u8),
        palette_index_and_flags,
        palette_triplet_index,
        shuffle_flags,
        obj_palette0: palette_bytes(obj0_offset),
        obj_palette1: palette_bytes(obj1_offset),
        bg_palette0: palette_bytes(bg_offset),
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct CgbCompatibilityPaletteBootInput {
    pressed_mask: u8,
}

impl CgbCompatibilityPaletteBootInput {
    #[cfg(test)]
    pub(crate) const fn none() -> Self {
        Self { pressed_mask: 0 }
    }

    pub(crate) const fn from_pressed_mask(pressed_mask: u8) -> Self {
        Self { pressed_mask }
    }

    fn override_index(self) -> Option<usize> {
        match self.pressed_mask {
            mask if mask == button_mask(JoypadButton::Up) => Some(0),
            mask if mask == (button_mask(JoypadButton::Up) | button_mask(JoypadButton::A)) => {
                Some(1)
            }
            mask if mask == (button_mask(JoypadButton::Up) | button_mask(JoypadButton::B)) => {
                Some(2)
            }
            mask if mask == button_mask(JoypadButton::Left) => Some(3),
            mask if mask == (button_mask(JoypadButton::Left) | button_mask(JoypadButton::A)) => {
                Some(4)
            }
            mask if mask == (button_mask(JoypadButton::Left) | button_mask(JoypadButton::B)) => {
                Some(5)
            }
            mask if mask == button_mask(JoypadButton::Down) => Some(6),
            mask if mask == (button_mask(JoypadButton::Down) | button_mask(JoypadButton::A)) => {
                Some(7)
            }
            mask if mask == (button_mask(JoypadButton::Down) | button_mask(JoypadButton::B)) => {
                Some(8)
            }
            mask if mask == button_mask(JoypadButton::Right) => Some(9),
            mask if mask == (button_mask(JoypadButton::Right) | button_mask(JoypadButton::A)) => {
                Some(10)
            }
            mask if mask == (button_mask(JoypadButton::Right) | button_mask(JoypadButton::B)) => {
                Some(11)
            }
            _ => None,
        }
    }
}

fn resolve_lookup_index(header: Option<&CartridgeHeader>) -> u8 {
    let Some(header) = header else {
        return CGB_COMPATIBILITY_DEFAULT_LOOKUP_INDEX;
    };

    let Some(checksum) = header.cgb_compatibility_title_checksum() else {
        return CGB_COMPATIBILITY_DEFAULT_LOOKUP_INDEX;
    };
    let Some(index) = TITLE_CHECKSUMS
        .iter()
        .position(|candidate| *candidate == checksum)
    else {
        return CGB_COMPATIBILITY_DEFAULT_LOOKUP_INDEX;
    };

    if index < TITLE_CHECKSUM_AMBIGUOUS_BASE_INDEX {
        return index as u8;
    }

    resolve_ambiguous_lookup_index(index, header.title_bytes[3])
        .unwrap_or(CGB_COMPATIBILITY_DEFAULT_LOOKUP_INDEX)
}

fn resolve_ambiguous_lookup_index(checksum_index: usize, fourth_title_byte: u8) -> Option<u8> {
    let column = checksum_index.checked_sub(TITLE_CHECKSUM_AMBIGUOUS_BASE_INDEX)?;
    let mut row_offset = column;

    while row_offset < TITLE_FOURTH_LETTERS.len() {
        if TITLE_FOURTH_LETTERS[row_offset] == fourth_title_byte {
            return Some((TITLE_CHECKSUM_AMBIGUOUS_BASE_INDEX + row_offset) as u8);
        }

        row_offset += TITLE_FOURTH_LETTER_ROW_BYTES;
    }

    None
}

fn palette_bytes(offset: u8) -> [u8; PALETTE_ENTRY_BYTES] {
    let offset = usize::from(offset);
    let mut bytes = [0; PALETTE_ENTRY_BYTES];
    bytes.copy_from_slice(&PALETTE_BYTES[offset..offset + PALETTE_ENTRY_BYTES]);
    bytes
}

#[cfg(test)]
fn rgb555_from_palette_bytes(palette: &[u8; PALETTE_ENTRY_BYTES], color_index: u8) -> u16 {
    let address = usize::from((color_index & 0x03) * 2);
    u16::from_le_bytes([palette[address], palette[address + 1]]) & 0x7FFF
}
